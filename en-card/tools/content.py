DEFAULT_LEVELS = (1, 2)

LEVEL_META = {
    1: ("第 1 级 · 身边", "动物、颜色、数字、家人、身体、最常吃的东西"),
    2: ("第 2 级 · 小词与教室", "句子里最常见的小词 + 文具、教室、玩具"),
    3: ("第 3 级 · 吃穿住", "食物、衣服、季节时间、星期、职业、家里和路上"),
    4: ("第 4 级 · 动作与学习", "课本里的课目 + 天天要用的动词"),
    5: ("第 5 级 · 描述与世界", "形容词、天气、地点、自然和运动"),
    6: ("第 6 级 · 想法与成长", "抽象名词 + 表达想法、态度和成长的动词"),
}


def build():
    seen = set()
    words = {}
    levels = {}
    for w, ipa, zh, lv in WORDS:
        assert w not in seen, "重复的单词：" + w
        assert ipa.startswith("/") and ipa.endswith("/"), "音标要带斜杠：" + w
        seen.add(w)
        words[w] = [ipa.strip("/"), zh]
        levels.setdefault(lv, []).append(w)

    phrases = {}
    for w, ipa, zh in EXTRA_WORDS:
        assert w not in words, "重复的单词：" + w
        words[w] = [ipa.strip("/"), zh]

    for p, zh in PHRASES:
        ws = p.split()
        assert 2 <= len(ws) <= 4, "短语只收 2~4 个词：" + p
        for w in ws:
            assert w in words, "短语里的词不在词表里：" + w + "（" + p + "）"
        if p in phrases:
            continue
        ipa = " ".join(words[w][0] for w in ws)
        phrases[p] = [ipa, zh]

    dict_data = {
        "version": 1,
        "updated": "2026-11-07",
        "note": "英语卡片词库。phrases 按词数分组，数组顺序即默认排序。defaultWords 是首次打开时的默认词库。",
        "defaultWords": [w for w, _, _, lv in WORDS if lv in DEFAULT_LEVELS],
        "phrases": {str(n): [p for p in phrases if len(p.split()) == n] for n in (2, 3, 4)},
    }

    phon_data = {
        "version": 1,
        "updated": "2026-11-07",
        "note": "音标（英式 DJ）+ 中文释义。words 是单词，phrases 是整句短语的音标。",
        "accent": "uk",
        "words": words,
        "phrases": phrases,
    }

    levels_data = {
        "version": 1,
        "updated": "2026-11-07",
        "note": "第 1~6 级分级词表，词和音标都指向 phon.json，这里只存顺序。",
        "levels": [
            {"level": lv, "name": LEVEL_META[lv][0], "note": LEVEL_META[lv][1], "words": levels[lv]}
            for lv in sorted(levels)
        ],
    }

    os.makedirs(DATA, exist_ok=True)
    for name, obj in (("dict", dict_data), ("phon", phon_data), ("levels", levels_data)):
        path = os.path.join(DATA, name + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(obj, f, ensure_ascii=False, indent=1)
        print("写出", os.path.relpath(path, ROOT), "%.0f KB" % (os.path.getsize(path) / 1024))

    print("单词 %d 个 · 短语 %d 条 · 默认词库 %d 个"
          % (len(words), len(phrases), len(dict_data["defaultWords"])))
    for lv in sorted(levels):
        print("  %s: %d 词" % (LEVEL_META[lv][0], len(levels[lv])))


if __name__ == "__main__":
    build()
